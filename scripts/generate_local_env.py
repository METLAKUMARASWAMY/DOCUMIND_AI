#!/usr/bin/env python3
from __future__ import annotations

import argparse
import secrets
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate ignored local and Docker secrets for DocuMind."
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace existing root and backend .env files.",
    )
    args = parser.parse_args()

    root_env = REPO_ROOT / ".env"
    backend_env = REPO_ROOT / "backend" / ".env"
    existing = [path for path in (root_env, backend_env) if path.exists()]
    if existing and not args.force:
        rendered = ", ".join(str(path.relative_to(REPO_ROOT)) for path in existing)
        raise SystemExit(f"Refusing to replace {rendered}; use --force intentionally.")

    auth_secret = secrets.token_urlsafe(48)
    postgres_password = secrets.token_urlsafe(24)
    neo4j_password = secrets.token_urlsafe(24)
    minio_access_key = f"documind_{secrets.token_hex(6)}"
    minio_secret_key = secrets.token_urlsafe(30)

    root_env.write_text(
        "\n".join(
            [
                "# Generated by scripts/generate_local_env.py; do not commit.",
                f"DOCUMIND_AUTH_SECRET={auth_secret}",
                "POSTGRES_USER=documind",
                f"POSTGRES_PASSWORD={postgres_password}",
                "POSTGRES_DB=documind",
                f"NEO4J_AUTH=neo4j/{neo4j_password}",
                f"MINIO_ACCESS_KEY={minio_access_key}",
                f"MINIO_SECRET_KEY={minio_secret_key}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    root_env.chmod(0o600)
    backend_env.write_text(
        "\n".join(
            [
                "# Generated by scripts/generate_local_env.py; do not commit.",
                "APP_ENV=local",
                f"DOCUMIND_AUTH_SECRET={auth_secret}",
                "DOCUMIND_AUTH_STATE_DIR=var/auth",
                "DOCUMIND_DATASET_PATH=../dataset/documind_ai_synthetic_dataset",
                "ENABLE_DEMO_API=false",
                "",
            ]
        ),
        encoding="utf-8",
    )
    backend_env.chmod(0o600)
    print("Generated .env and backend/.env with independent random service secrets.")


if __name__ == "__main__":
    main()
